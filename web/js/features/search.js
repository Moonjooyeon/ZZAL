/** 문장형 질문에서 의미 없는 토막 */
const STOP=['있어','있나','있는','없나','없어','없는','찾아줘','찾아','보여줘','알려줘','해줘','주세요','같은','관련','느낌','뭐가','뭔가','그런','이런','저런','하는','되는','에서','좀','거','것','때','나오는','나오는거','추천'];

/** 조사와 형용사 어미를 떼어 기본형 후보를 만듭니다 ("비둘기가"→"비둘기", "고된"→"고생") */
function stem(t) {
  const out = [];
  const s = t.replace(/(이랑|에서|으로|한테|에게|처럼|보다|까지|부터|랑|은|는|이|가|을|를|의|에|도|만|야|아|와|과)$/, '');
  if (s.length >= 2 && s !== t) out.push(s);
  if (/[은는운픈한던된난린인긴쁜른][\s]*$/.test(t) && t.length >= 3) out.push(t.slice(0, -1));
  if (/운$/.test(t) && t.length >= 3) out.push(t.slice(0, -1) + '움');
  if (/픈$/.test(t) && t.length >= 3) out.push(t.slice(0, -1) + '픔');
  if (/쁜$/.test(t) && t.length >= 3) out.push(t.slice(0, -1) + '쁨');
  if (/난$/.test(t) && t.length >= 3) out.push(t.slice(0, -1) + '남');
  return out.filter(x => x.length >= 2);
}

/** 검색어 한 줄 → 실제로 대조할 단어들 */
export function searchTerms(q) {
  let toks = q.split(/\s+/).filter(Boolean)
    .filter(t => !GENERIC.includes(t) && !STOP.includes(t));
  // 여러 단어를 넣었다면 한 글자짜리는 버립니다 ("때", "좀" 같은 게 전부를 물어옴)
  if (toks.length > 1) toks = toks.filter(t => t.length > 1);

  const out = [];
  toks.forEach(t => {
    const b = t.replace(/(짤|밈|짤방)$/, '');
    const base = b.length >= 2 ? b : t;
    out.push(base);
    const st = stem(base);
    st.forEach(x => out.push(x));
    [t, b, base, ...st].forEach(k => (SYN[k] || []).forEach(x => out.push(x)));
  });
  return [...new Set(out.filter(Boolean))];
}

/** 짤 하나가 이 검색어에 얼마나 맞는지 */
export function score(z, q, terms) {
  // 긴 문장으로 물어봤을 때: 숨은 키워드가 문장 안에 통째로 들어 있으면 가산
  let n = z.kw.reduce((s, k) => s + (k.length > 1 && q.includes(k) ? 2 : 0), 0);
  const name = z.name.toLowerCase();
  const why = String(z.why || '').replace(/<[^>]*>/g, '').toLowerCase();

  terms.forEach(t => {
    if (name.includes(t)) n += 4;
    if (z.tags.some(x => x.toLowerCase().includes(t))) n += 3;
    if (z.kw.some(k => k.toLowerCase().includes(t))) n += 2;
    if (why.includes(t)) n += 1;
    if (z.cat.toLowerCase().includes(t)) n += 1;
  });
  return n;
}

/** 목록을 검색어로 걸러 점수순으로 */
export function rank(rows, q) {
  const terms = searchTerms(q);
  if (!terms.length) return rows;
  return rows
    .map(z => ({ z, n: score(z, q, terms) }))
    .filter(x => x.n > 0)
    .sort((a, b) => b.n - a.n)
    .map(x => x.z);
}
